// «Сюжет недели»: как эта смена связана с другими кабинетами
export function teaser(profId, n, state) {
  const s = story(state);
  const done = (p, k) => !!state.profs?.[p]?.best?.[k];
  const T = [];
  if (profId === 'teller' && n === 1) {
    T.push(s.gran === 'saved'
      ? ['🛡', 'Валентина Петровна ещё вернётся: ночью «майор» позвонит ей снова — это дело отдела безопасности.']
      : ['🛡', 'Деньги Валентины Петровны ушли мошенникам. Отдел безопасности ещё может пойти по их следу.']);
    if (!done('advisor', 4) && state.difficulty !== 'easy') T.push(['📈', 'Артём, который платил штраф, скоро придёт к финансовому консультанту — за айфоном в кредит.']);
  }
  if (profId === 'credit' && n === 1) {
    T.push(s.maxim === 'saved'
      ? ['🛡', '«Друг» Руслан вербует молодёжь для мошенников. Их куратора вычисляют в отделе безопасности.']
      : ['🛡', 'Деньги за кредит Максима ушли мошенникам. Их куратора вычисляют в отделе безопасности.']);
  }
  if (profId === 'credit' && n === 4) T.push(['📈', s.artyom === 'reached' ? 'Артём копил с консультантом. Робот этого не видит — а человек может.' : 'Артём учился копить у финансового консультанта — загляни, как всё начиналось.']);
  if (profId === 'credit' && n === 5) T.push(['🚚', s.bakeryCash ? 'Инкассаторы каждое утро забирают выручку «Каравая» — ты видел эту пекарню на маршруте.' : 'Выручку «Каравая» каждое утро забирают инкассаторы — её видно на их маршруте.']);
  if (profId === 'advisor' && n === 1) T.push(['🛡', 'Ссылку «удвоим деньги» рассылают те же мошенники, что атакуют клиентов банка. Отдел безопасности уже на их следе.']);
  if (profId === 'advisor' && n === 4) T.push(['📝', 'Артём теперь копит на электровелосипед для работы — и придёт за кредитом к кредитному эксперту.']);
  if (profId === 'cash' && n === 1) {
    T.push(s.tail === 'caught'
      ? ['🛡', 'Серый седан работал на сеть мошенников. Их куратора вычисляют в отделе безопасности.']
      : ['🛡', 'Серый седан следил за броневиком. Чей он — выяснит отдел безопасности.']);
    if (!done('credit', 5)) T.push(['📝', 'Хозяйка «Каравая» хочет новую печь — её заявка придёт к кредитному эксперту.']);
  }
  if (profId === 'security' && n === 1) T.push(s.gran ? ['🧾', 'Одно СМС дошло до Валентины Петровны — той самой, что приходила к окну кассы. Ночью мошенники позвонят ей снова.'] : ['🧾', 'Одно СМС дошло до Валентины Петровны, 72 года. Ты её ещё встретишь — и у окна кассы, и ночью по телефону.']);
  if (profId === 'security' && n === 4 && s.gran) T.push(['🧾', s.gran === 'saved' ? 'Она тебя узнала: это ты был у окна кассы, когда она чуть не перевела деньги.' : 'В первый раз у окна кассы её не уберегли. Во второй раз — твоя очередь.']);
  if (profId === 'security' && n === 5) T.push(['🏦', 'Куратор стоял за всем: рассылкой, звонками «из банка», «друзьями» и серым седаном. Загляни к Галине Сергеевне в холл.']);
  return T.slice(0, 2);
}

