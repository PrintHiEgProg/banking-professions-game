// проверяет, что игрок уже видел, и подстраивается: напоминает о прошлом или намекает на будущее.
//
// Антагонист недели — сеть мошенников с «куратором» во главе (его вычисляют в смене 5 отдела безопасности).
// Её следы есть везде: фишинговая рассылка, звонки «из банка» Валентине Петровне, «друг» Максима,
// серый седан за броневиком, «удвоители» в игре Миши.

export const MENTOR = { id: 'mentor', name: 'Галина Сергеевна', role: 'управляющая отделением' };

export function story(state) {
  if (!state.story) state.story = {};
  return state.story;
}

// Сюжетное событие: запоминаем исход и кладём новость для наставника в холле
export function setBeat(state, key, value) {
  const s = story(state);
  if (s[key] === value) return;
  s[key] = value;
  s.news = [...(s.news || []).filter((n) => n !== key), key];
}

