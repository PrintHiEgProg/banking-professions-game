export function newsText(state, key) {
  const s = story(state);
  const fn = NEWS[key];
  return fn ? fn(s[key]) : null;
}

// Свежие новости: забираем из очереди
export function takeNews(state, n = 1) {
  const s = story(state);
  const all = s.news || [];
  const fresh = all.slice(0, n);
  s.news = all.slice(n);
  s.seen = [...(s.seen || []).filter((k) => !fresh.includes(k)), ...fresh].slice(-8);
  return fresh.map((k) => newsText(state, k)).filter(Boolean);
}

export function recentNews(state, n = 3) {
  const s = story(state);
  return [...(s.seen || [])].reverse().slice(0, n).map((k) => newsText(state, k)).filter(Boolean);
}

