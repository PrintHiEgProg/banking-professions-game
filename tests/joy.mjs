import { chromium } from 'playwright';
import { dismissMentor } from './mentor.inc.mjs';
import { audit } from './audit.inc.mjs';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/ERR_TUNNEL|net::|cbr-xml/.test(m.text())) errors.push(m.text()); });
await page.goto('http://localhost:8765/index.html?debug');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('bank.notours', '1'); localStorage.setItem('rubezh.settings.v1', JSON.stringify({ quality: 'low', sound: false })); });
await page.reload();
await page.waitForFunction(() => !document.querySelector('#loading.show'), null, { timeout: 30000 });
await page.fill('#nick', 'Левша');
await page.tap('#btn-joy');
await page.evaluate(() => document.querySelector('.title-links').scrollIntoView());
await page.waitForTimeout(400);
console.log('title audit', JSON.stringify(await audit(page, 'joy title')));
await page.screenshot({ path: 'shots/joy-title.png' });
console.log('label', await page.textContent('#btn-joy'), '| stats', await page.textContent('#btn-stats'));
await page.tap('#btn-start');
await page.waitForTimeout(400);
await page.tap('.intro-skip');
await dismissMentor(page, null);
await page.waitForTimeout(800);
const st = await page.evaluate(() => { const j = document.querySelector('#joystick').getBoundingClientRect(); return { joyLeft: Math.round(j.left), joyRight: Math.round(innerWidth - j.right), tut: document.querySelector('#tut li[data-id="walk"]')?.textContent }; });
console.log(JSON.stringify(st));
await page.screenshot({ path: 'shots/joy-right.png' });
await page.tap('#btn-pause');
await page.waitForTimeout(500);
console.log('pause has joy:', await page.isVisible('#p-joy'), await page.textContent('#p-joy'));
console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
await browser.close();
