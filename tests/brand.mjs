// Логотипы банка, табло курсов ЦБ, бегущая строка, часы, коврик — на высокой графике (со свечением).
// node brand.mjs [w] [h] [api=1|0]
import { chromium } from 'playwright';
import { dismissMentor } from './mentor.inc.mjs';
const [wArg = '1366', hArg = '768', apiArg = '1'] = process.argv.slice(2);
const tag = `br-${wArg}x${hArg}${apiArg === '1' ? '' : '-noapi'}`;
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: Number(wArg), height: Number(hArg) } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/ERR_TUNNEL|fonts\.g|cbr-xml-daily|ERR_FAILED|net::/.test(m.text())) errors.push('console: ' + m.text()); });
const sample = { Date: '2026-10-24T11:30:00+03:00', PreviousDate: '2026-10-23T11:30:00+03:00', Valute: { USD: { CharCode: 'USD', Nominal: 1, Value: 81.4521, Previous: 81.2033 }, EUR: { CharCode: 'EUR', Nominal: 1, Value: 94.8817, Previous: 95.1204 }, CNY: { CharCode: 'CNY', Nominal: 1, Value: 11.3912, Previous: 11.3912 } } };
if (apiArg === '1') await page.route('**/daily_json.js', (r) => r.fulfill({ status: 200, contentType: 'application/javascript', body: JSON.stringify(sample) }));
const wait = (ms) => page.waitForTimeout(ms);
const shot = (n) => page.screenshot({ path: `shots/${tag}-${n}.png` });
page.setDefaultTimeout(9000);
await page.goto('http://localhost:8765/index.html?debug');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('bank.notours', '1'); localStorage.setItem('rubezh.settings.v1', JSON.stringify({ quality: 'high', sound: false })); });
await page.reload();
await page.waitForFunction(() => !document.querySelector('#loading.show'), null, { timeout: 30000 });
await page.fill('#nick', 'Егор');
await wait(600);
await shot('00-title');
await page.click('#btn-start', { noWaitAfter: true });
await wait(400);
await page.click('.intro-skip');
await dismissMentor(page, null);
await page.evaluate(() => { document.querySelector('#tut')?.remove(); document.body.classList.remove('has-tut'); for (const s of ['#lock-hint', '#controls-hint']) document.querySelector(s)?.remove(); });
const pose = async (n, pos, yaw, pitch = 0, ms = 1600) => { await page.evaluate(([p, y, pt]) => window.__bank.controls.setPose(p, y, pt), [pos, yaw, pitch]); await wait(ms); await shot(n); };
await pose('01-hall', [0, 1.7, 7.0], 0, 0.02);
await pose('02-wall-logo', [-4.2, 1.7, -1.5], 0.12, 0.28);
await pose('03-header-board', [0.2, 1.7, -3.2], 0, 0.42);
await pose('04-atms-clock', [-6.0, 1.7, 5.6], Math.PI / 2, 0.12);
await pose('05-rates', [-6.6, 1.7, -6.0], Math.PI / 2, 0.22);
await pose('06-ticker', [4.4, 1.7, -3.6], -0.1, 0.38);
await pose('07-rollup', [0.8, 1.6, 4.4], -0.35, -0.12);
await pose('08-career', [5.9, 1.65, -0.9], -Math.PI / 2, 0);
await pose('09-mat', [0, 1.7, 5.4], Math.PI, -0.75);
const cap = await page.evaluate(() => window.__bank.world.rooms.lobby.captions.rates());
console.log('rates caption:', cap);
console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
await browser.close();
