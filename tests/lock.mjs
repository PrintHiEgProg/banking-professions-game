// Управление на ПК: клик захватывает мышь, камера следует за мышью, E — действие с тем, что в прицеле
import { chromium } from 'playwright';
import { dismissMentor } from './mentor.inc.mjs';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('ERR_TUNNEL')) errors.push('console: ' + m.text()); });
const shot = (n) => page.screenshot({ path: `shots/lock-${n}.png` });
await page.goto('http://localhost:8765/index.html?debug');
await page.evaluate(() => { localStorage.clear(); localStorage.setItem('bank.notours', '1'); localStorage.setItem('rubezh.settings.v1', JSON.stringify({ quality: 'low', sound: false })); });
await page.reload();
await page.waitForFunction(() => !document.querySelector('#loading.show'), null, { timeout: 30000 });
await page.fill('#nick', 'Тест');
await page.click('#btn-start');
await page.waitForTimeout(400);
await page.click('.intro-skip');
await dismissMentor(page);
await page.waitForTimeout(800);
const st = () => page.evaluate(() => ({ locked: document.pointerLockElement?.id || null, can: document.body.classList.contains('can-lock'), yaw: +window.__bank.controls.yaw.toFixed(3), hover: window.__bank.controls.hoverItem?.id || null, tut: [...document.querySelectorAll('#tut li.done')].map((l) => l.dataset.id) }));
console.log('before', JSON.stringify(await st()));
await page.mouse.click(683, 600);
await page.waitForTimeout(500);
console.log('after click', JSON.stringify(await st()));
await page.mouse.move(683, 600);
for (let i = 0; i < 10; i++) { await page.mouse.move(683 + (i + 1) * 30, 600); await page.waitForTimeout(30); }
await page.waitForTimeout(300);
console.log('after move', JSON.stringify(await st()));
// пройтись и навести прицел на терминал
await page.keyboard.down('KeyW'); await page.waitForTimeout(900); await page.keyboard.up('KeyW');
await page.evaluate(() => window.__bank.controls.setPose([0, 1.62, 4.6], 0, -0.25));
await page.waitForTimeout(400);
console.log('aim', JSON.stringify(await st()));
await page.waitForTimeout(1000);
console.log('after 1s', JSON.stringify(await st()));
console.log('manual', JSON.stringify(await page.evaluate(() => { const c = window.__bank.controls; c.update(0.016); return { hover: c.hoverItem?.id || null, key: c.hoverKey }; })));
console.log('dbg', JSON.stringify(await page.evaluate(() => { const c = window.__bank.controls; const THREE_pick = window.__bank.world.pick({ x: 0, y: 0 }, 7.5); return { enabled: c.enabled, locked: c.locked, tween: !!c.tween, pick: THREE_pick?.id || null, dist: THREE_pick?.dist, pos: window.__bank.world.camera.position.toArray().map((v) => +v.toFixed(2)) }; })));
await page.evaluate(() => document.dispatchEvent(new MouseEvent('mousemove', { movementX: 120, movementY: 0 })));
await page.waitForTimeout(200);
console.log('synthetic move', JSON.stringify(await st()));
await page.evaluate(() => window.__bank.controls.setPose([0, 1.62, 4.6], 0, -0.25));
await page.waitForTimeout(1200);
await shot('1-aim');
await page.keyboard.press('KeyE');
await page.waitForTimeout(1800);
const kiosk = await page.evaluate(() => !!document.querySelector('.kiosk-list'));
console.log('kiosk opened by E:', kiosk, JSON.stringify(await st()));
await shot('2-kiosk');
console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
await browser.close();
