import { chromium } from 'playwright';
import { dismissMentor } from './mentor.inc.mjs';
const URL = 'http://localhost:8765/index.html?debug';
const out = './shots';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(URL);
await page.waitForFunction(() => !document.querySelector('#loading.show'), null, { timeout: 30000 });
await page.screenshot({ path: `${out}/01-title.png` });
await page.fill('#nick', 'Тест');
await page.click('#btn-start');
await page.waitForTimeout(500);
await page.click('.intro-skip');
await dismissMentor(page);
await page.screenshot({ path: `${out}/02-lobby.png` });
// teller
await page.evaluate(() => window.__bank.enterRoomById('teller'));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/03-teller-cabinet.png` });
await page.click('.screen-card.cabinet .btn.primary');
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/04-teller-intro.png` });
await page.click('.intro-card-shift .btn.primary');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/05-teller-room.png` });
console.log('mode', await page.evaluate(() => window.__bank.mode));
console.log(errors.join('\n') || 'no errors');
await browser.close();
